# ======================================================================
# services パッケージ — ドメインロジック層
# ======================================================================
#
# 【役割】
#   ビュー（views/）から「HTTP の入出力」以外のロジックを切り出して
#   まとめる層。ビューは「フォームを受け取り → サービスを呼び → 結果を
#   テンプレート/リダイレクトへ返す」ことに専念できるようになる。
#
#   このパッケージに置くモジュール:
#     services/images.py   … 画像の検証・最適化・保存・削除
#     services/hashtags.py … ハッシュタグの解析・同期・孤立タグ掃除
#     services/captions.py … 画像キャプションのフォーム取得
#
#   なお images.py は、重い Pillow / filetype を「関数の内側」で遅延 import
#   する。これによりアプリ起動時（Blueprint 登録・import 時）に Pillow を
#   読み込まず、起動時間とベースメモリを節約できる。
# ======================================================================